import { globalStyle, style } from '@vanilla-extract/css';

/**
 * Базовый класс глифа. Значения — правило `.ti` витрины: коробка в кегль
 * текущего текста, глиф не сжимается во флекс-строке и садится на базовую
 * линию с оптическим сдвигом.
 *
 * Правило завёрнуто в `:where()` и потому имеет нулевую специфичность:
 * размер иконке назначает тот, кто её ставит — компонент своим CSS
 * или приложение своим классом, — и перебивать базовый стиль ему
 * не приходится.
 *
 * Цвет, заливка и толщина обводки заданы атрибутами самого `svg`,
 * а не здесь: так иконка выглядит правильно даже там, где таблицу стилей
 * пакета не подключили.
 */
export const icon = style({});

globalStyle(`:where(.${icon})`, {
  display: 'inline-block',
  inlineSize: '1em',
  blockSize: '1em',
  flex: '0 0 auto',
  verticalAlign: '-0.15em',
});

/**
 * Направленные глифы в RTL смотрят в другую сторону. Отражение сделано
 * свойством `scale`, а не `transform`: компоненты крутят те же иконки
 * трансформациями (Sidebar разворачивает шеврон раскрытой ветки, Tree —
 * маркер), и общий `transform` они бы друг другу затирали.
 */
globalStyle(`[dir="rtl"] .${icon}[data-rtl-mirror]`, {
  scale: '-1 1',
});
